CREATE TABLE IF NOT EXISTS users (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL, username VARCHAR(60) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role ENUM('cashier','owner') NOT NULL DEFAULT 'cashier', active BOOLEAN NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS customers (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(100) NOT NULL, phone VARCHAR(20) NOT NULL UNIQUE,
 address VARCHAR(300) NOT NULL DEFAULT '', notes VARCHAR(1000) NOT NULL DEFAULT '', created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS services (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, name VARCHAR(80) NOT NULL, price INT UNSIGNED NOT NULL, unit VARCHAR(16) NOT NULL,
 duration_hours INT UNSIGNED NULL, active BOOLEAN NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS orders (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, number VARCHAR(40) NULL UNIQUE, request_key VARCHAR(80) NOT NULL UNIQUE, request_hash CHAR(64) NULL,
 customer_id BIGINT NOT NULL, cashier_id BIGINT NOT NULL, customer_name VARCHAR(100) NOT NULL, customer_phone VARCHAR(20) NOT NULL,
 subtotal INT UNSIGNED NOT NULL, discount_percent DECIMAL(5,2) NULL, discount INT UNSIGNED NOT NULL DEFAULT 0, total INT UNSIGNED NOT NULL,
 method ENUM('cash','qris','transfer') NOT NULL, paid INT UNSIGNED NOT NULL, change_amount INT UNSIGNED NOT NULL,
 status ENUM('Diterima','Diproses','Selesai','Diambil') NOT NULL DEFAULT 'Diterima', notes VARCHAR(1000) NOT NULL DEFAULT '',
 created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, due_at DATETIME NULL,
 FOREIGN KEY(customer_id) REFERENCES customers(id), FOREIGN KEY(cashier_id) REFERENCES users(id),
 INDEX idx_orders_status_created(status,created_at)
);
CREATE TABLE IF NOT EXISTS order_items (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, service_id BIGINT NOT NULL,
 service_name VARCHAR(80) NOT NULL, unit VARCHAR(16) NOT NULL, price INT UNSIGNED NOT NULL,
 quantity DECIMAL(6,2) NOT NULL CHECK(quantity > 0), category VARCHAR(40) NOT NULL, subtotal INT UNSIGNED NOT NULL,
 FOREIGN KEY(order_id) REFERENCES orders(id), FOREIGN KEY(service_id) REFERENCES services(id)
);
CREATE TABLE IF NOT EXISTS status_history (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, status VARCHAR(20) NOT NULL,
 user_id BIGINT NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id), FOREIGN KEY(user_id) REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT PRIMARY KEY AUTO_INCREMENT, order_id BIGINT NOT NULL, status VARCHAR(24) NOT NULL,
 message VARCHAR(300) NOT NULL, created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY(order_id) REFERENCES orders(id)
);
CREATE TABLE IF NOT EXISTS login_attempts (
 ip_hash CHAR(64) PRIMARY KEY, attempts INT NOT NULL DEFAULT 0, last_attempt DATETIME NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
 id VARCHAR(128) PRIMARY KEY, data MEDIUMTEXT NOT NULL, updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
